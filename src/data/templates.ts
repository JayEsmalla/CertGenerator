import type {
  CertificateElement,
  CertificateTemplate,
  CertificateTextElement,
  TextAlign,
} from '../types/certificate'

const W = 1123
const H = 794

function text(
  id: string,
  name: string,
  value: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fontSize: number,
  color: string,
  options: Partial<Pick<CertificateTextElement, 'fontFamily' | 'fontWeight' | 'fontStyle' | 'textAlign' | 'letterSpacing' | 'lineHeight' | 'uppercase'>> = {},
): CertificateTextElement {
  return {
    id,
    name,
    type: 'text',
    text: value,
    x,
    y,
    width,
    height,
    fontSize,
    color,
    fontFamily: options.fontFamily ?? 'Inter, sans-serif',
    fontWeight: options.fontWeight ?? 400,
    fontStyle: options.fontStyle ?? 'normal',
    textAlign: (options.textAlign ?? 'center') as TextAlign,
    letterSpacing: options.letterSpacing ?? 0,
    lineHeight: options.lineHeight ?? 1.25,
    uppercase: options.uppercase ?? false,
  }
}

function frame(stroke: string, inset = 34): CertificateElement {
  return {
    id: `frame-${stroke.replace('#', '')}-${inset}`,
    name: 'Decorative frame',
    type: 'shape',
    x: inset,
    y: inset,
    width: W - inset * 2,
    height: H - inset * 2,
    fill: 'transparent',
    stroke,
    strokeWidth: 3,
    locked: true,
  }
}

