import type {
  CertificateElement,
  CertificateImageElement,
  CertificateImageSlot,
  CertificatePalette,
  CertificateQuickField,
  CertificateShapeElement,
  CertificateTemplate,
  CertificateTextElement,
  TextAlign,
} from '../types/certificate'

const W = 1123
const H = 794

function text(
  id: string,
  name: string,
  value: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fontSize: number,
  color: string,
  options: Partial<Pick<CertificateTextElement, 'fontFamily' | 'fontWeight' | 'fontStyle' | 'textAlign' | 'letterSpacing' | 'lineHeight' | 'uppercase'>> = {},
): CertificateTextElement {
  return {
    id,
    name,
    type: 'text',
    text: value,
    x,
    y,
    width,
    height,
    fontSize,
    color,
    fontFamily: options.fontFamily ?? 'Inter, sans-serif',
    fontWeight: options.fontWeight ?? 400,
    fontStyle: options.fontStyle ?? 'normal',
    textAlign: (options.textAlign ?? 'center') as TextAlign,
    letterSpacing: options.letterSpacing ?? 0,
    lineHeight: options.lineHeight ?? 1.25,
    uppercase: options.uppercase ?? false,
  }
}

function shape(
  id: string,
  name: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fill: string,
  options: Partial<Pick<CertificateShapeElement, 'stroke' | 'strokeWidth' | 'borderRadius' | 'opacity' | 'rotation' | 'locked'>> = {},
): CertificateShapeElement {
  return {
    id,
    name,
    type: 'shape',
    x,
    y,
    width,
    height,
    fill,
    stroke: options.stroke,
    strokeWidth: options.strokeWidth,
    borderRadius: options.borderRadius,
    opacity: options.opacity ?? 1,
    rotation: options.rotation,
    locked: options.locked ?? true,
  }
}

function rule(id: string, name: string, x: number, y: number, width: number, color: string, thickness = 1): CertificateElement {
  return { id, name, type: 'line', x, y, width, height: Math.max(thickness, 2), color, thickness, locked: true }
}

function frame(id: string, stroke: string, inset: number, width = 2): CertificateElement {
  return shape(id, 'Decorative frame', inset, inset, W - inset * 2, H - inset * 2, 'transparent', { stroke, strokeWidth: width, locked: true })
}

function imageSlot(
  id: string,
  name: string,
  slotKey: string,
  label: string,
  x: number,
  y: number,
  width: number,
  height: number,
  borderRadius = 0,
): CertificateImageElement {
  return { id, name, type: 'image', slotKey, placeholderLabel: label, x, y, width, height, objectFit: 'contain', borderRadius }
}

function mergeField(key: string, label: string, group: CertificateQuickField['group'], placeholder: string, required = true): CertificateQuickField {
  return { key, label, group, source: 'merge', placeholder, required }
}

function elementField(key: string, label: string, group: CertificateQuickField['group'], elementId: string, placeholder: string): CertificateQuickField {
  return { key, label, group, source: 'element', elementId, placeholder, required: true }
}

function premium(details: {
  purpose: string
  style: string
  tags: string[]
  palette: CertificatePalette
  sampleData: Record<string, string>
  quickFields: CertificateQuickField[]
  imageSlots?: CertificateImageSlot[]
}): Pick<CertificateTemplate, 'purpose' | 'style' | 'tags' | 'palette' | 'sampleData' | 'defaults' | 'quickFields' | 'imageSlots'> {
  const defaults = Object.fromEntries(details.quickFields.filter((field) => field.source !== 'element').map((field) => [field.key, '']))
  return { ...details, defaults, imageSlots: details.imageSlots ?? [] }
}

