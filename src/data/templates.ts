const W = 1123
const H = 794

function text(
  id: string,
  name: string,
  value: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fontSize: number,
  color: string,
  options: Partial<Pick<CertificateTextElement, 'fontFamily' | 'fontWeight' | 'fontStyle' | 'textAlign' | 'letterSpacing' | 'lineHeight' | 'uppercase' | 'autoFit' | 'minFontSize'>> = {},
): CertificateTextElement {
  const autoFit = options.autoFit ?? (value.includes('{{name}}') || value.includes('{{organization}}') || fontSize >= 36)
  return {
    id,
    name,
    type: 'text',
    text: value,
    x,
    y,
    width,
    height,
    fontSize,
    color,
    fontFamily: options.fontFamily ?? 'Inter, sans-serif',
    fontWeight: options.fontWeight ?? 400,
    fontStyle: options.fontStyle ?? 'normal',
    textAlign: (options.textAlign ?? 'center') as TextAlign,
    letterSpacing: options.letterSpacing ?? 0,
    lineHeight: options.lineHeight ?? 1.25,
    uppercase: options.uppercase ?? false,
    autoFit,
    minFontSize: options.minFontSize ?? (autoFit ? Math.min(fontSize, Math.max(8, Math.round(fontSize * 0.42))) : undefined),
  }
}

function shape(
  id: string,
  name: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fill: string,
  options: Partial<Pick<CertificateShapeElement, 'stroke' | 'strokeWidth' | 'borderRadius' | 'opacity' | 'rotation' | 'locked'>> = {},
): CertificateShapeElement {
  return {
    id,
    name,
    type: 'shape',
    x,
    y,
    width,
    height,
    fill,
    stroke: options.stroke,
    strokeWidth: options.strokeWidth,
    borderRadius: options.borderRadius,
    opacity: options.opacity ?? 1,
    rotation: options.rotation,
    locked: options.locked ?? true,
  }
}

function rule(id: string, name: string, x: number, y: number, width: number, color: string, thickness = 1): CertificateElement {
  return { id, name, type: 'line', x, y, width, height: Math.max(thickness, 2), color, thickness, locked: true }
}

function frame(id: string, stroke: string, inset: number, width = 2): CertificateElement {
  return shape(id, 'Decorative frame', inset, inset, W - inset * 2, H - inset * 2, 'transparent', { stroke, strokeWidth: width, locked: true })
}

function svgDataUri(svg: string) {
  return `data:image/svg+xml;charset=UTF-8,${encodeURIComponent(svg)}`
}

